// fakeServer is an in-process KVService and AdminService with a simple
// in-memory store and scriptable failures. Every behaviour knob is guarded by
// mu so tests can change it while the client runs.
type fakeServer struct {
	kvorumpb.UnimplementedKVServiceServer
	kvorumpb.UnimplementedAdminServiceServer

	id   uint64
	addr string
	srv  *grpc.Server

	mu       sync.Mutex
	rev      uint64
	data     map[string]*kvorumpb.KeyValue
	sessions []*kvorumpb.Session
	calls    map[string]int

	// leaderAddr, when set, makes every request fail with Unavailable and a
	// LeaderHint pointing at it. leaderHintCode overrides the code used.
	leaderAddr     string
	leaderHintCode codes.Code
	// failNext makes the next n requests fail with failErr.
	failNext int
	failErr  error
	// alwaysErr makes every request fail with the given error.
	alwaysErr error

	// watchers receive the events generated by writes.
	watchers map[chan *kvorumpb.WatchResponse]struct{}
	// watchErr, when set, makes Watch fail immediately.
	watchErr error
	// watchEOF makes Watch end cleanly after the first event.
	watchEOF bool

	members []*kvorumpb.Member
}

func startFakeServer(t *testing.T, id uint64) *fakeServer {
	t.Helper()
	lis, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatalf("listen: %v", err)
	}
	f := &fakeServer{
		id:       id,
		addr:     lis.Addr().String(),
		srv:      grpc.NewServer(),
		data:     make(map[string]*kvorumpb.KeyValue),
		calls:    make(map[string]int),
		watchers: make(map[chan *kvorumpb.WatchResponse]struct{}),
	}
	f.members = []*kvorumpb.Member{{Id: id, RaftAddress: "raft-" + f.addr, ClientAddress: f.addr}}
	kvorumpb.RegisterKVServiceServer(f.srv, f)
	kvorumpb.RegisterAdminServiceServer(f.srv, f)
	done := make(chan struct{})
	go func() {
		defer close(done)
		_ = f.srv.Serve(lis)
	}()
	t.Cleanup(func() {
		f.srv.Stop()
		<-done
	})
	return f
}

func (f *fakeServer) setLeader(addr string) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.leaderAddr = addr
}

func (f *fakeServer) setLeaderHintCode(c codes.Code) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.leaderHintCode = c
}

func (f *fakeServer) failNextWith(n int, err error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.failNext = n
	f.failErr = err
}

func (f *fakeServer) failAlwaysWith(err error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.alwaysErr = err
}

func (f *fakeServer) callCount(method string) int {
	f.mu.Lock()
	defer f.mu.Unlock()
	return f.calls[method]
}

func (f *fakeServer) recordedSessions() []*kvorumpb.Session {
	f.mu.Lock()
	defer f.mu.Unlock()
	out := make([]*kvorumpb.Session, len(f.sessions))
	copy(out, f.sessions)
	return out
}

// gate applies the scripted failures. It must be called with mu held.
func (f *fakeServer) gateLocked(method string) error {
	f.calls[method]++
	if f.leaderAddr != "" {
		code := codes.Unavailable
		if f.leaderHintCode != codes.OK {
			code = f.leaderHintCode
		}
		st, err := status.New(code, "not the leader").WithDetails(&kvorumpb.LeaderHint{LeaderId: 99, LeaderAddress: f.leaderAddr})
		if err != nil {
			return err
		}
		return st.Err()
	}
	if f.alwaysErr != nil {
		return f.alwaysErr
	}
	if f.failNext > 0 {
		f.failNext--
		return f.failErr
	}
	return nil
}

func (f *fakeServer) header() *kvorumpb.ResponseHeader {
	return &kvorumpb.ResponseHeader{MemberId: f.id, Term: 7, Revision: f.rev}
}

func cloneKV(kv *kvorumpb.KeyValue) *kvorumpb.KeyValue {
	if kv == nil {
		return nil
	}
	return &kvorumpb.KeyValue{
		Key:            bytes.Clone(kv.Key),
		Value:          bytes.Clone(kv.Value),
		Version:        kv.Version,
		CreateRevision: kv.CreateRevision,
		ModRevision:    kv.ModRevision,
	}
}

func (f *fakeServer) broadcastLocked(ev *kvorumpb.Event) {
	for ch := range f.watchers {
		select {
		case ch <- &kvorumpb.WatchResponse{Header: f.header(), Events: []*kvorumpb.Event{ev}}:
		default:
		}
	}
}

func (f *fakeServer) Get(_ context.Context, req *kvorumpb.GetRequest) (*kvorumpb.GetResponse, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	if req.GetConsistency() == kvorumpb.ReadConsistency_READ_CONSISTENCY_STALE {
		f.calls["Get.stale"]++
	}
	if err := f.gateLocked("Get"); err != nil {
		return nil, err
	}
	kv, ok := f.data[string(req.GetKey())]
	return &kvorumpb.GetResponse{Header: f.header(), Found: ok, Kv: cloneKV(kv)}, nil
}

func (f *fakeServer) Put(_ context.Context, req *kvorumpb.PutRequest) (*kvorumpb.PutResponse, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.sessions = append(f.sessions, req.GetSession())
	if err := f.gateLocked("Put"); err != nil {
		return nil, err
	}
	f.rev++
	key := string(req.GetKey())
	prev := f.data[key]
	kv := &kvorumpb.KeyValue{Key: bytes.Clone(req.GetKey()), Value: bytes.Clone(req.GetValue()), Version: 1, CreateRevision: f.rev, ModRevision: f.rev}
	if prev != nil {
		kv.Version = prev.Version + 1
		kv.CreateRevision = prev.CreateRevision
	}
	f.data[key] = kv
	f.broadcastLocked(&kvorumpb.Event{Type: kvorumpb.Event_TYPE_PUT, Kv: cloneKV(kv), PrevKv: cloneKV(prev)})
	resp := &kvorumpb.PutResponse{Header: f.header(), Kv: cloneKV(kv)}
	if req.GetPrevKv() {
		resp.PrevKv = cloneKV(prev)
	}
	return resp, nil
}

func (f *fakeServer) Delete(_ context.Context, req *kvorumpb.DeleteRequest) (*kvorumpb.DeleteResponse, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.sessions = append(f.sessions, req.GetSession())
	if err := f.gateLocked("Delete"); err != nil {
		return nil, err
	}
	key := string(req.GetKey())
	prev, ok := f.data[key]
	resp := &kvorumpb.DeleteResponse{Header: f.header(), Deleted: ok}
	if ok {
		f.rev++
		delete(f.data, key)
		resp.Header = f.header()
		f.broadcastLocked(&kvorumpb.Event{
			Type:   kvorumpb.Event_TYPE_DELETE,
			Kv:     &kvorumpb.KeyValue{Key: bytes.Clone(req.GetKey()), ModRevision: f.rev},
			PrevKv: cloneKV(prev),
		})
		if req.GetPrevKv() {
			resp.PrevKv = cloneKV(prev)
		}
	}
	return resp, nil
}

func (f *fakeServer) CompareAndSwap(_ context.Context, req *kvorumpb.CompareAndSwapRequest) (*kvorumpb.CompareAndSwapResponse, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.sessions = append(f.sessions, req.GetSession())
	if err := f.gateLocked("CompareAndSwap"); err != nil {
		return nil, err
	}
	key := string(req.GetKey())
	cur := f.data[key]
	var curVersion uint64
	if cur != nil {
		curVersion = cur.Version
	}
	if curVersion != req.GetExpectedVersion() {
		return &kvorumpb.CompareAndSwapResponse{Header: f.header(), Succeeded: false, Kv: cloneKV(cur)}, nil
	}
	f.rev++
	kv := &kvorumpb.KeyValue{Key: bytes.Clone(req.GetKey()), Value: bytes.Clone(req.GetValue()), Version: curVersion + 1, CreateRevision: f.rev, ModRevision: f.rev}
	if cur != nil {
		kv.CreateRevision = cur.CreateRevision
	}
	f.data[key] = kv
	return &kvorumpb.CompareAndSwapResponse{Header: f.header(), Succeeded: true, Kv: cloneKV(kv)}, nil
}

func (f *fakeServer) Scan(_ context.Context, req *kvorumpb.ScanRequest) (*kvorumpb.ScanResponse, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	if err := f.gateLocked("Scan"); err != nil {
		return nil, err
	}
	keys := make([]string, 0, len(f.data))
	for k := range f.data {
		if bytes.Compare([]byte(k), req.GetStart()) < 0 {
			continue
		}
		if len(req.GetEnd()) > 0 && bytes.Compare([]byte(k), req.GetEnd()) >= 0 {
			continue
		}
		keys = append(keys, k)
	}
	sort.Strings(keys)
	resp := &kvorumpb.ScanResponse{Header: f.header()}
	for _, k := range keys {
		if req.GetLimit() > 0 && int64(len(resp.Kvs)) >= req.GetLimit() {
			resp.More = true
			break
		}
		resp.Kvs = append(resp.Kvs, cloneKV(f.data[k]))
	}
	return resp, nil
}

func (f *fakeServer) Watch(req *kvorumpb.WatchRequest, stream kvorumpb.KVService_WatchServer) error {
	f.mu.Lock()
	if err := f.gateLocked("Watch"); err != nil {
		f.mu.Unlock()
		return err
	}
	if f.watchErr != nil {
		f.mu.Unlock()
		return f.watchErr
	}
	eof := f.watchEOF
	ch := make(chan *kvorumpb.WatchResponse, 64)
	f.watchers[ch] = struct{}{}
	f.mu.Unlock()
	defer func() {
		f.mu.Lock()
		delete(f.watchers, ch)
		f.mu.Unlock()
	}()
	for {
		select {
		case <-stream.Context().Done():
			return stream.Context().Err()
		case resp := <-ch:
			filtered := &kvorumpb.WatchResponse{Header: resp.Header}
			for _, ev := range resp.Events {
				if inWatchRange(ev.GetKv().GetKey(), req.GetKey(), req.GetRangeEnd()) {
					filtered.Events = append(filtered.Events, ev)
				}
			}
			if len(filtered.Events) == 0 {
				continue
			}
			if err := stream.Send(filtered); err != nil {
				return err
			}
			if eof {
				return nil
			}
		}
	}
}

func inWatchRange(key, start, end []byte) bool {
	if len(end) == 0 {
		return bytes.Equal(key, start)
	}
	return bytes.Compare(key, start) >= 0 && bytes.Compare(key, end) < 0
}

func (f *fakeServer) Status(context.Context, *kvorumpb.StatusRequest) (*kvorumpb.StatusResponse, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	if err := f.gateLocked("Status"); err != nil {
		return nil, err
	}
	return &kvorumpb.StatusResponse{
		Header:        f.header(),
		Id:            f.id,
		State:         "leader",
		Term:          7,
		Leader:        f.id,
		CommitIndex:   f.rev,
		AppliedIndex:  f.rev,
		LastIndex:     f.rev,
		SnapshotIndex: 0,
		Members:       f.members,
		Version:       "test",
	}, nil
}

func (f *fakeServer) ListMembers(context.Context, *kvorumpb.ListMembersRequest) (*kvorumpb.ListMembersResponse, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	if err := f.gateLocked("ListMembers"); err != nil {
		return nil, err
	}
	return &kvorumpb.ListMembersResponse{Header: f.header(), Members: f.members, Leader: f.id}, nil
}

func (f *fakeServer) AddMember(_ context.Context, req *kvorumpb.AddMemberRequest) (*kvorumpb.AddMemberResponse, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	if err := f.gateLocked("AddMember"); err != nil {
		return nil, err
	}
	for _, m := range f.members {
		if m.GetId() == req.GetMember().GetId() {
			return nil, status.Error(codes.AlreadyExists, "member exists")
		}
	}
	f.members = append(f.members, req.GetMember())
	return &kvorumpb.AddMemberResponse{Header: f.header(), Members: f.members}, nil
}

func (f *fakeServer) RemoveMember(_ context.Context, req *kvorumpb.RemoveMemberRequest) (*kvorumpb.RemoveMemberResponse, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	if err := f.gateLocked("RemoveMember"); err != nil {
		return nil, err
	}
	kept := f.members[:0]
	found := false
	for _, m := range f.members {
		if m.GetId() == req.GetId() {
			found = true
			continue
		}
		kept = append(kept, m)
	}
	if !found {
		return nil, status.Error(codes.NotFound, "no such member")
	}
	f.members = kept
	return &kvorumpb.RemoveMemberResponse{Header: f.header(), Members: f.members}, nil
}

func (f *fakeServer) PromoteMember(_ context.Context, req *kvorumpb.PromoteMemberRequest) (*kvorumpb.PromoteMemberResponse, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	if err := f.gateLocked("PromoteMember"); err != nil {
		return nil, err
	}
	for _, m := range f.members {
		if m.GetId() == req.GetId() {
			m.Learner = false
			return &kvorumpb.PromoteMemberResponse{Header: f.header(), Members: f.members}, nil
		}
	}
	return nil, status.Error(codes.NotFound, "no such member")
}

func (f *fakeServer) TransferLeadership(_ context.Context, req *kvorumpb.TransferLeadershipRequest) (*kvorumpb.TransferLeadershipResponse, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	if err := f.gateLocked("TransferLeadership"); err != nil {
		return nil, err
	}
	for _, m := range f.members {
		if m.GetId() == req.GetTargetId() {
			return &kvorumpb.TransferLeadershipResponse{Header: f.header()}, nil
		}
	}
	return nil, status.Error(codes.InvalidArgument, "unknown target")
}

func (f *fakeServer) Snapshot(context.Context, *kvorumpb.SnapshotRequest) (*kvorumpb.SnapshotResponse, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	if err := f.gateLocked("Snapshot"); err != nil {
		return nil, err
	}
	return &kvorumpb.SnapshotResponse{Header: f.header(), SnapshotIndex: f.rev}, nil
}
